<#
.SYNOPSIS
  Writes the Google Play licensing public key into the game (D-183 receipt check).

.DESCRIPTION
  Play Console > SoloHero > Monetize with Play > Monetization setup > Licensing: copy the "Base64-encoded RSA public
  key" and pass it as -Key. The script checks that it is a real RSA public key, masks it and writes
  Assets/SoloHero/Scripts/Game/Infrastructure/PlayLicenseKey.cs (commit that file - it is a public key).
  Release builds refuse to build without it, and every Google Play receipt is checked against it: a purchase whose
  signature does not match (a fake billing app) is never paid.

.EXAMPLE
  pwsh tools/release/SetPlayLicenseKey.ps1 -Key "MIIBIjANBgkqhkiG9w0BAQEFAAOCAQ8AMIIBCgKCAQEA..."
#>
param(
    [Parameter(Mandatory = $true)][string]$Key
)

$ErrorActionPreference = 'Stop'
$clean = ($Key -replace '\s', '')
try {
    $bytes = [Convert]::FromBase64String($clean)
} catch {
    throw "Not base64: copy the whole key from Play Console > Monetization setup > Licensing."
}

if ($bytes.Length -lt 200 -or $bytes.Length -gt 1200 -or $bytes[0] -ne 0x30) {
    throw "This does not look like the licensing public key ($($bytes.Length) bytes)."
}

$rsa = [System.Security.Cryptography.RSA]::Create()
try {
    $read = 0
    $rsa.ImportSubjectPublicKeyInfo($bytes, [ref]$read)
    if ($read -ne $bytes.Length) { throw "trailing bytes" }
    $bits = $rsa.KeySize
} catch {
    throw "Not an RSA public key: $($_.Exception.Message)"
} finally {
    $rsa.Dispose()
}

$mask = [byte[]]::new($bytes.Length)
[System.Security.Cryptography.RandomNumberGenerator]::Fill($mask)
$masked = [byte[]]::new($bytes.Length)
for ($i = 0; $i -lt $bytes.Length; $i++) {
    $masked[$i] = [byte](($bytes[$i] -bxor $mask[$i] -bxor (($i * 167 + 29) -band 0xFF)) -band 0xFF)
}

function Format-Bytes([byte[]]$data) {
    $lines = @()
    for ($i = 0; $i -lt $data.Length; $i += 24) {
        $end = [Math]::Min($i + 24, $data.Length) - 1
        $lines += '            ' + (($data[$i..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', ') + ','
    }
    return ($lines -join "`n")
}

$out = Join-Path $PSScriptRoot '..\..\Assets\SoloHero\Scripts\Game\Infrastructure\PlayLicenseKey.cs'
$text = @"
// <auto-generated>
// Written by tools/release/SetPlayLicenseKey.ps1 - do not edit by hand.
// The Google Play licensing public key (Play Console > the app > Monetize > Monetization setup > Licensing), masked so
// it is not one searchable run of bytes in the build. It is a public key: committing it is safe.
// Empty until the developer runs the script; release builds refuse to build without it (BuildAutomator).
// </auto-generated>
namespace SoloHero.Game.Infrastructure
{
    public static class PlayLicenseKey
    {
        private static readonly byte[] Masked =
        {
$(Format-Bytes $masked)
        };

        private static readonly byte[] Mask =
        {
$(Format-Bytes $mask)
        };

        public static bool Present => Masked.Length > 0 && Masked.Length == Mask.Length;

        /// <summary>The key's DER bytes (X.509 SubjectPublicKeyInfo), or an empty array before the script ran.</summary>
        public static byte[] Get()
        {
            if (!Present) return new byte[0];
            var key = new byte[Masked.Length];
            for (int i = 0; i < key.Length; i++) key[i] = (byte)(Masked[i] ^ Mask[i] ^ (byte)(i * 167 + 29));
            return key;
        }
    }
}
"@
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $out)).Path + '\PlayLicenseKey.cs', $text.Replace("`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))

$sha = [System.Security.Cryptography.SHA256]::HashData($bytes)
Write-Host "RSA $bits-bit key written to Assets/SoloHero/Scripts/Game/Infrastructure/PlayLicenseKey.cs"
Write-Host ("SHA-256 of the key: " + (($sha | ForEach-Object { $_.ToString('x2') }) -join ''))
Write-Host "Commit the file, then run the Release AAB workflow."
